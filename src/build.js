// Everything the page can actually render: element text, attributes that surface
// as text (alt/aria-label/title/placeholder/content), CSS content: strings, and
// string literals in the inline scripts. Deliberately over-inclusive -- a false
// alarm costs one character in fonts.charset.txt, a miss costs tofu in production.
function assertCharsetCovers(html, label) {
  const covered = new Set(Array.from(CHARSET));
  ["\n", "\r", "\t"].forEach(c => covered.add(c));
  const decoded = html
    .replace(/&middot;/g, "·").replace(/&minus;/g, "−")
    .replace(/&rarr;/g, "→").replace(/&larr;/g, "←")
    .replace(/&darr;/g, "↓").replace(/&uarr;/g, "↑")
    .replace(/&mdash;/g, "—").replace(/&ndash;/g, "–")
    .replace(/&hellip;/g, "…").replace(/&copy;/g, "©")
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(+d))
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)));
  const missing = new Map();
  for (const ch of decoded) if (!covered.has(ch)) missing.set(ch, (missing.get(ch) || 0) + 1);
  if (missing.size) {
    const list = [...missing].map(([c, n]) => `U+${c.codePointAt(0).toString(16).toUpperCase().padStart(4, "0")} ${JSON.stringify(c)} x${n}`);
    throw new Error(
      `${label}: ${missing.size} codepoint(s) outside the font subset -- these would render as tofu:\n  ` +
      list.join("\n  ") + `\nAdd them to src/fonts.charset.txt and re-run subset-fonts.py.`);
  }
}

