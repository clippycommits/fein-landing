// The *.subset.woff2 files are generated by subset-fonts.py: the full faces are
// a 100-900 weight axis over the whole Latin set, and this site renders 128
// codepoints at the three weight ranges the @font-face descriptors already
// clamp to. Subsetting is therefore lossless and takes 101 KB of font down to
// 42 KB, which is a third of the wire weight of the page.
//
// The risk that buys is tofu: add a character the subset lacks and the browser
// falls back mid-word. assertCharsetCovers below closes that off by failing the
// BUILD instead, so the failure lands here and not on a visitor's screen.
